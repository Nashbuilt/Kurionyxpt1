-- Owner-only income classification and Monzo credit reconciliation.
-- Additive only: no existing bank, sales, expense or inventory records are rewritten.

begin;

select pg_advisory_xact_lock(hashtext('kurionyx:bank_income_classification'));

do $$
begin
  if to_regclass('public.workspaces') is null or to_regclass('public.workspace_members') is null then
    raise exception 'Income classification prerequisites are missing.'
      using hint = 'Apply the repository migrations in order before continuing.';
  end if;
end $$;

create table if not exists public.income_records (
  id bigint generated by default as identity primary key,
  workspace_id bigint not null references public.workspaces(id) on delete cascade,
  description text not null check (char_length(trim(description)) between 1 and 240),
  category text not null check (char_length(trim(category)) between 1 and 80),
  income_date date not null default current_date,
  amount numeric(12,2) not null check (amount >= 0),
  payment_reference text check (payment_reference is null or char_length(payment_reference) <= 240),
  notes text not null default '' check (char_length(notes) <= 2000),
  source_provider text not null default 'manual' check (source_provider in ('manual', 'monzo')),
  external_transaction_id text,
  data_status text not null default 'unverified' check (data_status in ('verified', 'unverified', 'demonstration')),
  archived_at timestamptz,
  archived_by uuid references auth.users(id) on delete set null,
  archive_reason text check (archive_reason is null or char_length(archive_reason) <= 500),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists income_records_workspace_date_idx
  on public.income_records (workspace_id, income_date desc);
create unique index if not exists income_records_workspace_external_tx_uidx
  on public.income_records (workspace_id, external_transaction_id)
  where external_transaction_id is not null;

drop trigger if exists set_income_records_updated_at on public.income_records;
create trigger set_income_records_updated_at before update on public.income_records
for each row execute function private.set_updated_at();

alter table public.income_records enable row level security;

drop policy if exists income_records_owner_select on public.income_records;
create policy income_records_owner_select on public.income_records for select to authenticated
using (exists (
  select 1 from public.workspace_members member
  where member.workspace_id = income_records.workspace_id
    and member.user_id = auth.uid() and member.role = 'owner'
));

revoke all on table public.income_records from public, anon, authenticated;
grant select on table public.income_records to authenticated;
grant usage, select on sequence public.income_records_id_seq to authenticated;

create or replace function public.save_bank_income(
  p_workspace_id bigint, p_income_id bigint, p_description text, p_category text,
  p_income_date date, p_amount numeric, p_payment_reference text, p_notes text,
  p_data_status text, p_external_transaction_id text
)
returns bigint language plpgsql security definer set search_path = '' as $$
declare
  saved_id bigint;
  transaction_id text := nullif(trim(coalesce(p_external_transaction_id, '')), '');
  reference text := nullif(trim(coalesce(p_payment_reference, '')), '');
begin
  if auth.uid() is null then raise exception 'Authentication required.' using errcode = '42501'; end if;
  if not exists (
    select 1 from public.workspace_members member
    where member.workspace_id = p_workspace_id and member.user_id = auth.uid() and member.role = 'owner'
  ) then raise exception 'Only the workspace owner can classify bank income.' using errcode = '42501'; end if;
  if char_length(trim(coalesce(p_description, ''))) not between 1 and 240 then raise exception 'Income description is required.' using errcode = '22023'; end if;
  if char_length(trim(coalesce(p_category, ''))) not between 1 and 80 then raise exception 'Income category is required.' using errcode = '22023'; end if;
  if p_income_date is null then raise exception 'Income date is required.' using errcode = '22023'; end if;
  if p_amount is null or p_amount < 0 then raise exception 'Income amount cannot be negative.' using errcode = '22023'; end if;
  if char_length(coalesce(p_notes, '')) > 2000 then raise exception 'Income notes are too long.' using errcode = '22023'; end if;
  if p_data_status not in ('verified', 'unverified', 'demonstration') then raise exception 'Invalid record status.' using errcode = '22023'; end if;

  if p_income_id is null then
    insert into public.income_records (
      workspace_id, description, category, income_date, amount, payment_reference,
      notes, source_provider, external_transaction_id, data_status
    ) values (
      p_workspace_id, trim(p_description), trim(p_category), p_income_date, p_amount,
      reference, trim(coalesce(p_notes, '')), case when transaction_id is null then 'manual' else 'monzo' end,
      transaction_id, p_data_status
    ) returning id into saved_id;
  else
    update public.income_records income
    set description = trim(p_description), category = trim(p_category), income_date = p_income_date,
        amount = p_amount, payment_reference = reference, notes = trim(coalesce(p_notes, '')),
        source_provider = case when transaction_id is null then 'manual' else 'monzo' end,
        external_transaction_id = transaction_id, data_status = p_data_status
    where income.id = p_income_id and income.workspace_id = p_workspace_id and income.archived_at is null
    returning income.id into saved_id;
    if saved_id is null then raise exception 'Income record not found in this workspace.' using errcode = 'P0002'; end if;
  end if;
  return saved_id;
end;
$$;

create or replace function public.archive_income_record(p_income_id bigint, p_reason text)
returns void language plpgsql security definer set search_path = '' as $$
begin
  if auth.uid() is null then raise exception 'Authentication required.' using errcode = '42501'; end if;
  if char_length(trim(coalesce(p_reason, ''))) not between 3 and 500 then raise exception 'An archive reason is required.' using errcode = '22023'; end if;
  update public.income_records income
  set archived_at = now(), archived_by = auth.uid(), archive_reason = trim(p_reason)
  where income.id = p_income_id and income.archived_at is null and exists (
    select 1 from public.workspace_members member
    where member.workspace_id = income.workspace_id and member.user_id = auth.uid() and member.role = 'owner'
  );
  if not found then raise exception 'Income record not found or access denied.' using errcode = '42501'; end if;
end;
$$;

revoke all on function public.save_bank_income(bigint, bigint, text, text, date, numeric, text, text, text, text) from public, anon;
grant execute on function public.save_bank_income(bigint, bigint, text, text, date, numeric, text, text, text, text) to authenticated;
revoke all on function public.archive_income_record(bigint, text) from public, anon;
grant execute on function public.archive_income_record(bigint, text) to authenticated;

commit;
