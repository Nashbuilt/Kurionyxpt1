begin;

select pg_advisory_xact_lock(hashtext('kurionyx:documents_vault'));

create table if not exists public.business_documents (
  id bigint generated by default as identity primary key,
  workspace_id bigint not null references public.workspaces(id) on delete restrict,
  category text not null check (category in ('legal', 'receipt', 'other')),
  title text not null check (char_length(trim(title)) between 2 and 240),
  document_date date,
  notes text not null default '' check (char_length(notes) <= 4000),
  original_file_name text not null check (char_length(original_file_name) between 1 and 255),
  storage_path text not null check (char_length(storage_path) between 10 and 1000),
  mime_type text not null check (mime_type in ('application/pdf', 'image/jpeg', 'image/png', 'image/webp')),
  size_bytes bigint not null check (size_bytes between 1 and 20971520),
  sha256_hex text not null check (sha256_hex ~ '^[0-9a-f]{64}$'),
  version_number integer not null default 1 check (version_number > 0),
  archived_at timestamptz,
  archived_by uuid references auth.users(id) on delete set null,
  created_by uuid not null references auth.users(id) on delete restrict,
  created_at timestamptz not null default now(),
  unique (workspace_id, id),
  unique (workspace_id, storage_path)
);

create table if not exists public.document_signatures (
  id bigint generated by default as identity primary key,
  workspace_id bigint not null references public.workspaces(id) on delete restrict,
  document_id bigint not null,
  signer_user_id uuid not null references auth.users(id) on delete restrict,
  signer_name text not null check (char_length(trim(signer_name)) between 2 and 200),
  consent_statement text not null,
  document_sha256_hex text not null check (document_sha256_hex ~ '^[0-9a-f]{64}$'),
  signed_at timestamptz not null default now(),
  foreign key (workspace_id, document_id) references public.business_documents(workspace_id, id) on delete restrict,
  unique (document_id, signer_user_id)
);

create index if not exists business_documents_workspace_category_idx
  on public.business_documents(workspace_id, category, created_at desc) where archived_at is null;
create index if not exists document_signatures_workspace_document_idx
  on public.document_signatures(workspace_id, document_id, signed_at);

alter table public.business_documents enable row level security;
alter table public.document_signatures enable row level security;

create policy "Members can view business documents" on public.business_documents for select to authenticated
using (exists (select 1 from public.workspace_members member where member.workspace_id = business_documents.workspace_id and member.user_id = (select auth.uid())));

create policy "Members can view document signatures" on public.document_signatures for select to authenticated
using (exists (select 1 from public.workspace_members member where member.workspace_id = document_signatures.workspace_id and member.user_id = (select auth.uid())));

insert into storage.buckets(id, name, public, file_size_limit, allowed_mime_types)
values ('business-documents', 'business-documents', false, 20971520, array['application/pdf','image/jpeg','image/png','image/webp'])
on conflict (id) do update set public = false, file_size_limit = excluded.file_size_limit, allowed_mime_types = excluded.allowed_mime_types;

create policy "Workspace members can read business documents" on storage.objects for select to authenticated
using (bucket_id = 'business-documents' and (storage.foldername(name))[1] ~ '^[0-9]+$' and exists (
  select 1 from public.workspace_members member where member.workspace_id = ((storage.foldername(name))[1])::bigint and member.user_id = (select auth.uid())
));

create policy "Members can upload business documents" on storage.objects for insert to authenticated
with check (bucket_id = 'business-documents' and (storage.foldername(name))[1] ~ '^[0-9]+$'
  and (storage.foldername(name))[2] = (select auth.uid())::text and exists (
    select 1 from public.workspace_members member where member.workspace_id = ((storage.foldername(name))[1])::bigint and member.user_id = (select auth.uid())
  ));

create policy "Uploaders can clean up unregistered documents" on storage.objects for delete to authenticated
using (bucket_id = 'business-documents' and owner_id = (select auth.uid())::text and not exists (
  select 1 from public.business_documents document where document.storage_path = name
));

create or replace function public.create_business_document(
  p_workspace_id bigint, p_category text, p_title text, p_document_date date,
  p_notes text, p_original_file_name text, p_storage_path text,
  p_mime_type text, p_size_bytes bigint, p_sha256_hex text
) returns bigint language plpgsql security definer set search_path = '' as $$
declare
  current_user_id uuid := auth.uid();
  expected_prefix text;
  new_id bigint;
begin
  if current_user_id is null then raise exception 'Authentication required.' using errcode = '42501'; end if;
  if not exists (select 1 from public.workspace_members member where member.workspace_id = p_workspace_id and member.user_id = current_user_id) then
    raise exception 'Workspace access required.' using errcode = '42501';
  end if;
  expected_prefix := p_workspace_id::text || '/' || current_user_id::text || '/';
  if left(p_storage_path, char_length(expected_prefix)) <> expected_prefix then raise exception 'Invalid document path.' using errcode = '22023'; end if;
  if not exists (select 1 from storage.objects object where object.bucket_id = 'business-documents' and object.name = p_storage_path) then
    raise exception 'Uploaded document was not found.' using errcode = '22023';
  end if;

  insert into public.business_documents(workspace_id, category, title, document_date, notes, original_file_name, storage_path, mime_type, size_bytes, sha256_hex, created_by)
  values (p_workspace_id, p_category, trim(p_title), p_document_date, coalesce(trim(p_notes), ''), p_original_file_name, p_storage_path, p_mime_type, p_size_bytes, lower(p_sha256_hex), current_user_id)
  returning id into new_id;
  return new_id;
end;
$$;

create or replace function public.sign_business_document(p_document_id bigint, p_consent boolean, p_confirmation text)
returns bigint language plpgsql security definer set search_path = '' as $$
declare
  target public.business_documents%rowtype;
  signer_name_value text;
  signature_id bigint;
  fixed_statement constant text := 'I have reviewed this exact document version and intend to sign it electronically.';
begin
  if auth.uid() is null then raise exception 'Authentication required.' using errcode = '42501'; end if;
  if p_consent is not true or upper(trim(coalesce(p_confirmation, ''))) <> 'I AGREE' then raise exception 'Signature confirmation is required.' using errcode = '22023'; end if;

  select * into target from public.business_documents document
  where document.id = p_document_id and document.category = 'legal' and document.archived_at is null
    and exists (select 1 from public.workspace_members member where member.workspace_id = document.workspace_id and member.user_id = auth.uid())
  for share;
  if target.id is null then raise exception 'Legal document not found or access denied.' using errcode = '42501'; end if;

  select coalesce(nullif(trim(member.display_name), ''), account.email, auth.uid()::text) into signer_name_value
  from public.workspace_members member left join auth.users account on account.id = member.user_id
  where member.workspace_id = target.workspace_id and member.user_id = auth.uid();

  insert into public.document_signatures(workspace_id, document_id, signer_user_id, signer_name, consent_statement, document_sha256_hex)
  values (target.workspace_id, target.id, auth.uid(), signer_name_value, fixed_statement, target.sha256_hex)
  returning id into signature_id;
  return signature_id;
exception when unique_violation then
  raise exception 'You have already signed this document version.' using errcode = '23505';
end;
$$;

create or replace function public.archive_business_document(p_document_id bigint)
returns void language plpgsql security definer set search_path = '' as $$
begin
  if auth.uid() is null then raise exception 'Authentication required.' using errcode = '42501'; end if;
  update public.business_documents document set archived_at = now(), archived_by = auth.uid()
  where document.id = p_document_id and document.archived_at is null and exists (
    select 1 from public.workspace_members member where member.workspace_id = document.workspace_id and member.user_id = auth.uid()
  );
  if not found then raise exception 'Document not found or access denied.' using errcode = '42501'; end if;
end;
$$;

revoke all on table public.business_documents, public.document_signatures from public, anon, authenticated;
grant select on table public.business_documents, public.document_signatures to authenticated;
revoke all on function public.create_business_document(bigint,text,text,date,text,text,text,text,bigint,text) from public, anon;
revoke all on function public.sign_business_document(bigint,boolean,text) from public, anon;
revoke all on function public.archive_business_document(bigint) from public, anon;
grant execute on function public.create_business_document(bigint,text,text,date,text,text,text,text,bigint,text) to authenticated;
grant execute on function public.sign_business_document(bigint,boolean,text) to authenticated;
grant execute on function public.archive_business_document(bigint) to authenticated;

commit;
