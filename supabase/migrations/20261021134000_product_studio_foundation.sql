begin;

create table if not exists public.product_opportunities (
  id bigint generated by default as identity primary key,
  workspace_id bigint not null references public.workspaces(id) on delete restrict,
  name text not null check (char_length(trim(name)) between 2 and 200),
  category text not null check (char_length(trim(category)) between 2 and 100),
  proposed_sku text,
  supplier_name text,
  supplier_url text check (supplier_url is null or supplier_url ~* '^https?://'),
  source_url text check (source_url is null or source_url ~* '^https?://'),
  marketplace text not null default 'Amazon',
  research_status text not null default 'idea'
    check (research_status in ('idea', 'researching', 'sample_ordered', 'approved', 'rejected', 'converted')),
  confidence text not null default 'low' check (confidence in ('low', 'medium', 'high')),
  estimated_unit_cost numeric(12,2) not null default 0 check (estimated_unit_cost >= 0),
  estimated_shipping_cost numeric(12,2) not null default 0 check (estimated_shipping_cost >= 0),
  estimated_marketplace_fees numeric(12,2) not null default 0 check (estimated_marketplace_fees >= 0),
  target_sale_price numeric(12,2) not null default 0 check (target_sale_price >= 0),
  estimated_monthly_sales integer not null default 0 check (estimated_monthly_sales >= 0),
  notes text not null default '' check (char_length(notes) <= 4000),
  linked_stock_item_id bigint,
  archived_at timestamptz,
  archived_by uuid references auth.users(id) on delete set null,
  created_by uuid not null default auth.uid() references auth.users(id) on delete restrict,
  updated_by uuid not null default auth.uid() references auth.users(id) on delete restrict,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint product_opportunities_linked_stock_workspace_fk
    foreign key (workspace_id, linked_stock_item_id)
    references public.stock_items(workspace_id, id) on delete restrict,
  constraint product_opportunities_conversion_consistent
    check ((research_status = 'converted') = (linked_stock_item_id is not null))
);

create index if not exists product_opportunities_workspace_status_idx
  on public.product_opportunities(workspace_id, research_status)
  where archived_at is null;

alter table public.product_opportunities enable row level security;

create policy "Members can view product opportunities"
on public.product_opportunities for select to authenticated
using (exists (
  select 1 from public.workspace_members member
  where member.workspace_id = product_opportunities.workspace_id
    and member.user_id = auth.uid()
));

create policy "Members can create product opportunities"
on public.product_opportunities for insert to authenticated
with check (
  created_by = auth.uid() and updated_by = auth.uid()
  and exists (
    select 1 from public.workspace_members member
    where member.workspace_id = product_opportunities.workspace_id
      and member.user_id = auth.uid()
  )
);

create policy "Members can update product opportunities"
on public.product_opportunities for update to authenticated
using (exists (
  select 1 from public.workspace_members member
  where member.workspace_id = product_opportunities.workspace_id
    and member.user_id = auth.uid()
))
with check (exists (
  select 1 from public.workspace_members member
  where member.workspace_id = product_opportunities.workspace_id
    and member.user_id = auth.uid()
));

drop trigger if exists product_opportunities_set_record_actor on public.product_opportunities;
create trigger product_opportunities_set_record_actor
before insert or update on public.product_opportunities
for each row execute function private.set_record_actor();

create or replace function public.promote_product_opportunity(
  p_opportunity_id bigint,
  p_sku text,
  p_initial_units bigint,
  p_unit_cost numeric,
  p_data_status text
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  opportunity public.product_opportunities%rowtype;
  stock_item_id bigint;
begin
  if auth.uid() is null then raise exception 'Authentication required.' using errcode = '42501'; end if;

  select * into opportunity
  from public.product_opportunities item
  where item.id = p_opportunity_id
    and item.archived_at is null
    and exists (
      select 1 from public.workspace_members member
      where member.workspace_id = item.workspace_id and member.user_id = auth.uid()
    )
  for update;

  if opportunity.id is null then raise exception 'Product opportunity not found or access denied.' using errcode = '42501'; end if;
  if opportunity.linked_stock_item_id is not null then raise exception 'This product is already linked to stock.' using errcode = '23505'; end if;

  stock_item_id := public.create_stock_item(
    opportunity.workspace_id,
    opportunity.name,
    opportunity.category,
    p_sku,
    p_initial_units,
    p_unit_cost,
    0,
    0,
    concat('Created from Product Studio research #', opportunity.id, '. ', opportunity.notes),
    p_data_status
  );

  update public.product_opportunities
  set linked_stock_item_id = stock_item_id,
      research_status = 'converted'
  where id = opportunity.id;

  return stock_item_id;
end;
$$;

create or replace function public.archive_product_opportunity(p_opportunity_id bigint)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if auth.uid() is null then raise exception 'Authentication required.' using errcode = '42501'; end if;

  update public.product_opportunities item
  set archived_at = now(), archived_by = auth.uid()
  where item.id = p_opportunity_id
    and item.archived_at is null
    and exists (
      select 1 from public.workspace_members member
      where member.workspace_id = item.workspace_id and member.user_id = auth.uid()
    );

  if not found then raise exception 'Product opportunity not found or access denied.' using errcode = '42501'; end if;
end;
$$;

revoke all on table public.product_opportunities from public, anon, authenticated;
grant select, insert on table public.product_opportunities to authenticated;
grant update (
  name, category, proposed_sku, supplier_name, supplier_url, source_url,
  marketplace, research_status, confidence, estimated_unit_cost,
  estimated_shipping_cost, estimated_marketplace_fees, target_sale_price,
  estimated_monthly_sales, notes
) on table public.product_opportunities to authenticated;
grant usage, select on sequence public.product_opportunities_id_seq to authenticated;
revoke all on function public.promote_product_opportunity(bigint, text, bigint, numeric, text) from public, anon;
grant execute on function public.promote_product_opportunity(bigint, text, bigint, numeric, text) to authenticated;
revoke all on function public.archive_product_opportunity(bigint) from public, anon;
grant execute on function public.archive_product_opportunity(bigint) to authenticated;

commit;
